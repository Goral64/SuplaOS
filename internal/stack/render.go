const generatedList = ".suplaos-files"

// header starts every file generated in the stack directory.
const header = "# Generated by suplaos, changes are overwritten.\n# Use 'suplaos config <add-on> KEY=VALUE' instead.\n"

// Plan is the content of the stack directory for the installed add-ons.
type Plan struct {
	// ComposeFiles in COMPOSE_FILE order.
	ComposeFiles []string
	// Files to write, by name in the stack directory.
	Files map[string][]byte
	// Env is the .env of the project.
	Env []addon.KV
	// Dirs to create in the stack directory.
	Dirs []string
	// Owner is the add-on that brings each file ("suplaos" for .env).
	Owner map[string]string
}

// Order returns the installed add-ons, each after the add-ons it requires.
func (s *Stack) Order() []*addon.Addon {
	var out []*addon.Addon
	done := map[string]bool{}
	var visit func(id string)
	visit = func(id string) {
		if done[id] || !s.IsInstalled(id) {
			return
		}
		done[id] = true
		a := s.Catalog[id]
		for _, r := range a.Requires {
			visit(r)
		}
		out = append(out, a)
	}
	ids := make([]string, 0, len(s.State.Addons))
	for id := range s.State.Addons {
		ids = append(ids, id)
	}
	sort.Strings(ids)
	for _, id := range ids {
		visit(id)
	}
	return out
}

// Values returns the option values of an installed add-on: stored values
// over defaults.
func (s *Stack) Values(a *addon.Addon) map[string]string {
	v := map[string]string{}
	for i := range a.Options {
		v[a.Options[i].Key] = DefaultValue(&a.Options[i])
	}
	if inst := s.State.Addons[a.ID]; inst != nil {
		for k, val := range inst.Options {
			v[k] = val
		}
	}
	return v
}

// Active tells whether the option applies to the current setup.
func (s *Stack) Active(o *addon.Option, values map[string]string) bool {
	return o.When.Match(s.IsInstalled, s.withOthers(values))
}

// withOthers adds the option values of the other installed add-ons as
// "<add-on>:<KEY>", for conditions on them.
func (s *Stack) withOthers(values map[string]string) map[string]string {
	all := map[string]string{}
	for _, a := range s.Order() {
		for k, v := range s.Values(a) {
			all[a.ID+":"+k] = v
		}
	}
	for k, v := range values {
		all[k] = v
	}
	return all
}

// Plan builds the stack directory content from the state.
func (s *Stack) Plan() (*Plan, error) {
	p := &Plan{Files: map[string][]byte{}, Owner: map[string]string{}}
	env := &envList{}
	env.set("COMPOSE_PROJECT_NAME", ProjectName)
	env.set("COMPOSE_FILE", "")
	env.set("VOLUME_DATA", "./var")
	env.set("TZ", s.TZ)
	// Address of the device for settings shown to clients, e.g. the MQTT
	// broker in Supla Cloud.
	env.set("SUPLAOS_IP", PrimaryIP())
	globals := map[string]bool{}
	for _, kv := range env.list {
		globals[kv.Key] = true
	}

	owner := map[string]string{}
	add := func(id, name string, data []byte) error {
		if o, ok := owner[name]; ok {
			return fmt.Errorf("%s and %s both bring %s", o, id, name)
		}
		owner[name] = id
		p.Owner[name] = id
		p.Files[name] = data
		return nil
	}

	for _, a := range s.Order() {
		values := s.Values(a)
		for _, f := range a.Files {
			data, err := s.source(a, f)
			if err != nil {
				return nil, err
			}
			if err := add(a.ID, f, data); err != nil {
				return nil, err
			}
		}
		for _, c := range a.Compose {
			if !c.When.Match(s.IsInstalled, s.withOthers(values)) {
				continue
			}
			data, err := s.source(a, c.File)
			if err != nil {
				return nil, err
			}
			if err := add(a.ID, c.File, data); err != nil {
				return nil, err
			}
			p.ComposeFiles = append(p.ComposeFiles, c.File)
		}

		env.comment(a.ID)
		// own collects the .env variables of this add-on alone, for its
		// env_file: containers get them without the variables of other
		// add-ons, so installing those does not recreate them.
		own := &envList{}
		own.set("TZ", s.TZ)
		setEnv := func(k, v string) {
			env.set(k, v)
			own.set(k, v)
		}
		if a.EnvBase != "" {
			data, err := s.source(a, a.EnvBase)
			if err != nil {
				return nil, err
			}
			base, err := parseEnv(data)
			if err != nil {
				return nil, fmt.Errorf("%s: %s: %w", a.ID, a.EnvBase, err)
			}
			for _, kv := range base {
				if !globals[kv.Key] {
					setEnv(kv.Key, kv.Value)
				}
			}
		}
		for _, kv := range a.FixedEnv {
			setEnv(kv.Key, kv.Value)
		}

		files := map[string]*envList{}
		var names []string
		for i := range a.Options {
			o := &a.Options[i]
			if o.File != "" && files[o.File] == nil {
				files[o.File] = &envList{}
				names = append(names, o.File)
			}
			if !s.Active(o, values) {
				continue
			}
			// Empty values are left out, unless they replace a default.
			v := values[o.Key]
			if o.File == "" {
				if v != "" || env.has(o.Key) {
					setEnv(o.Key, v)
				}
			} else if v != "" {
				files[o.File].set(o.Key, v)
			}
		}
		if a.EnvFile != "" {
			if files[a.EnvFile] != nil {
				return nil, fmt.Errorf("%s: env_file %s is also an option file", a.ID, a.EnvFile)
			}
			if err := add(a.ID, a.EnvFile, own.render()); err != nil {
				return nil, err
			}
		}
		for _, name := range names {
			if err := add(a.ID, name, files[name].render()); err != nil {
				return nil, err
			}
		}
		p.Dirs = append(p.Dirs, a.Dirs...)
	}

	env.set("COMPOSE_FILE", strings.Join(p.ComposeFiles, ":"))
	p.Env = env.list
	if err := add("suplaos", ".env", env.render()); err != nil {
		return nil, err
	}
	return p, nil
}

// source reads a file of the add-on from the catalog or, for downloaded
// files, from the cache.
func (s *Stack) source(a *addon.Addon, name string) ([]byte, error) {
	data, err := os.ReadFile(filepath.Join(a.Dir, name))
	if errors.Is(err, os.ErrNotExist) && a.Fetch != nil {
		data, err = os.ReadFile(filepath.Join(s.cacheDir(a.ID), name))
	}
	if err != nil {
		return nil, fmt.Errorf("%s: %w", a.ID, err)
	}
	return data, nil
}

// Write puts the plan into the stack directory and removes files generated
// before that are no longer needed.
func (s *Stack) Write(p *Plan) error {
	dir := s.Dir()
	if err := s.mkdir(dir); err != nil {
		return err
	}
	for _, d := range p.Dirs {
		if err := s.mkdir(filepath.Join(dir, d)); err != nil {
			return err
		}
	}
	var names []string
	for name, data := range p.Files {
		perm := os.FileMode(0o644)
		if strings.HasSuffix(name, ".env") || strings.HasPrefix(name, ".env") {
			perm = 0o600
		}
		if err := s.writeFile(filepath.Join(dir, name), data, perm); err != nil {
			return err
		}
		names = append(names, name)
	}
	sort.Strings(names)

	old, _ := os.ReadFile(filepath.Join(dir, generatedList))
	for _, name := range strings.Fields(string(old)) {
		if _, ok := p.Files[name]; !ok && filepath.IsLocal(name) {
			os.Remove(filepath.Join(dir, name))
		}
	}
	return s.writeFile(filepath.Join(dir, generatedList), []byte(strings.Join(names, "\n")+"\n"), 0o644)
}

// reservedPorts are used by the system itself.
var reservedPorts = map[int]string{22: "SSH", 80: "the SuplaOS panel", 8443: "the SuplaOS panel"}

// CheckPorts makes sure no two add-ons publish the same host port.
func (s *Stack) CheckPorts(p *Plan) error {
	env := map[string]string{}
	for _, kv := range p.Env {
		env[kv.Key] = kv.Value
	}
	used := map[int]string{}
	for port, who := range reservedPorts {
		used[port] = who
	}
	for _, a := range s.Order() {
		values := s.Values(a)
		for _, spec := range a.Ports {
			if !spec.When.Match(s.IsInstalled, s.withOthers(values)) {
				continue
			}
			v := os.Expand(spec.Port, func(k string) string { return env[k] })
			if v == "" {
				continue
			}
			port, err := strconv.Atoi(v)
			if err != nil || port < 1 || port > 65535 {
				return fmt.Errorf("%s: invalid port %q", a.ID, v)
			}
			if who, ok := used[port]; ok && who != a.ID {
				return fmt.Errorf("%s: port %d is already used by %s", a.ID, port, who)
			}
			used[port] = a.ID
		}
	}
	return nil
}

// Pending returns the installed add-ons whose files in the stack directory
// differ from what the catalog brings now, e.g. after an update of
// SuplaOS. Apply (and Up) puts the new files in place.
func (s *Stack) Pending() ([]string, error) {
	p, err := s.Plan()
	if err != nil {
		return nil, err
	}
	pending := map[string]bool{}
	for name, data := range p.Files {
		id := p.Owner[name]
		if id == "suplaos" {
			continue
		}
		disk, err := os.ReadFile(filepath.Join(s.Dir(), name))
		if err != nil || !bytes.Equal(disk, data) {
			pending[id] = true
		}
	}
	for _, a := range s.Order() {
		if a.Fetch == nil {
			continue
		}
		if src, err := os.ReadFile(filepath.Join(s.cacheDir(a.ID), sourceFile)); err != nil || string(src) != a.Fetch.URL {
			pending[a.ID] = true
		}
	}
	var out []string
	for _, a := range s.Order() {
		if pending[a.ID] {
			out = append(out, a.ID)
		}
	}
	return out, nil
}

// Expand replaces ${VAR} with values from the .env of the project, e.g.
// the port of an add-on web interface.
func (s *Stack) Expand(str string) string {
	p, err := s.Plan()
	if err != nil {
		return ""
	}
	env := map[string]string{}
	for _, kv := range p.Env {
		env[kv.Key] = kv.Value
	}
	return os.Expand(str, func(k string) string { return env[k] })
}

// Apply writes the stack directory for the current state.
func (s *Stack) Apply() error {
	filled := s.fillGenerated()
	p, err := s.Plan()
	if err != nil {
		return err
	}
	if err := s.CheckPorts(p); err != nil {
		return err
	}
	if err := s.Write(p); err != nil {
		return err
	}
	if err := s.certificates(); err != nil {
		return err
	}
	if filled {
		return s.Save()
	}
	return nil
}

// fillGenerated generates values of installed add-ons that have none yet,
// e.g. a password added to the add-on after it was installed.
func (s *Stack) fillGenerated() bool {
	filled := false
	for _, a := range s.Order() {
		inst := s.State.Addons[a.ID]
		for _, o := range a.Options {
			if o.Generate > 0 && inst.Options[o.Key] == "" {
				inst.Options[o.Key] = randomString(o.Generate)
				filled = true
			}
		}
	}
	return filled
}

type envList struct {
	list []addon.KV
	// comments before the variable at the given index.
	comments map[int][]string
	pending  string
}

func (e *envList) set(key, value string) {
	for i := range e.list {
		if e.list[i].Key == key {
			e.list[i].Value = value
			return
		}
	}
	if e.pending != "" {
		if e.comments == nil {
			e.comments = map[int][]string{}
		}
		e.comments[len(e.list)] = append(e.comments[len(e.list)], e.pending)
		e.pending = ""
	}
	e.list = append(e.list, addon.KV{Key: key, Value: value})
}

func (e *envList) has(key string) bool {
	for _, kv := range e.list {
		if kv.Key == key {
			return true
		}
	}
	return false
}

// comment is written before the next new variable, if there is one.
func (e *envList) comment(text string) {
	e.pending = text
}

func (e *envList) render() []byte {
	var b bytes.Buffer
	b.WriteString(header)
	for i, kv := range e.list {
		for _, c := range e.comments[i] {
			fmt.Fprintf(&b, "\n# %s\n", c)
		}
		fmt.Fprintf(&b, "%s=%s\n", kv.Key, quote(kv.Value))
	}
	return b.Bytes()
}

// quote writes a value so that docker compose reads it literally.
func quote(v string) string {
	if v == "" {
		return ""
	}
	for _, r := range v {
		if !(r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9' || strings.ContainsRune("._-/:@,+=", r)) {
			return "'" + v + "'"
		}
	}
	return v
}

// parseEnv reads KEY=VALUE lines of a dotenv file.
func parseEnv(data []byte) ([]addon.KV, error) {
	var out []addon.KV
	sc := bufio.NewScanner(bytes.NewReader(data))
	for n := 1; sc.Scan(); n++ {
		line := strings.TrimSpace(sc.Text())
		if line == "" || line[0] == '#' {
			continue
		}
		line = strings.TrimPrefix(line, "export ")
		k, v, ok := strings.Cut(line, "=")
		if !ok {
			return nil, fmt.Errorf("line %d: expected KEY=VALUE", n)
		}
		v = strings.TrimSpace(v)
		if len(v) >= 2 && (v[0] == '"' || v[0] == '\'') && v[len(v)-1] == v[0] {
			v = v[1 : len(v)-1]
		}
		out = append(out, addon.KV{Key: strings.TrimSpace(k), Value: v})
	}
	return out, sc.Err()
}
